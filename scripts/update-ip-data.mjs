#!/usr/bin/env node
// Refreshes the IP data efsp bundles. Nothing is fetched by
// the app itself at runtime; this script runs at development/build time.
//
//   node scripts/update-ip-data.mjs --ranges   cloud IP ranges       -> crates/core/data/cloud-ranges.tsv (committed)
//   node scripts/update-ip-data.mjs --geo      DB-IP Lite databases  -> src-tauri/resources/ipdb/ (not committed)
//
// Sources (official URLs only):
//   Google Cloud  https://www.gstatic.com/ipranges/cloud.json
//   AWS           https://ip-ranges.amazonaws.com/ip-ranges.json
//   DB-IP Lite    https://db-ip.com/db/lite.php  (CC BY 4.0: "IP Geolocation by DB-IP")

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { gunzipSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res;
}

async function ranges() {
  const google = await (await get("https://www.gstatic.com/ipranges/cloud.json")).json();
  const aws = await (await get("https://ip-ranges.amazonaws.com/ip-ranges.json")).json();
  // cidr -> region (first wins). Region codes alone identify a city, so
  // they must not repeat across sources.
  const rows = new Map();
  const googleRegions = new Set();
  for (const p of google.prefixes) {
    const cidr = p.ipv4Prefix ?? p.ipv6Prefix;
    if (cidr && p.scope && p.scope !== "global") {
      rows.set(cidr, p.scope);
      googleRegions.add(p.scope);
    }
  }
  // EC2 only: that's where game servers run, and each EC2 range really is
  // in its region. Other AWS services (Global Accelerator, CloudFront, …)
  // are listed under a region but serve everywhere, so blocking a city by
  // them would block far more than that city.
  for (const p of [...aws.prefixes, ...aws.ipv6_prefixes]) {
    const cidr = p.ip_prefix ?? p.ipv6_prefix;
    if (cidr && p.service === "EC2" && p.region && p.region !== "GLOBAL" && !rows.has(cidr)) {
      if (googleRegions.has(p.region)) throw new Error(`region code ${p.region} is in both lists`);
      rows.set(cidr, p.region);
    }
  }
  const lines = [...rows].map(([cidr, region]) => `${cidr}\t${region}`).sort();
  const header = [
    `# Cloud IP ranges for efsp (cidr, region).`,
    `# Generated by scripts/update-ip-data.mjs on ${new Date().toISOString().slice(0, 10)}.`,
    `# Google Cloud: cloud.json ${google.creationTime ?? ""}; AWS: ip-ranges.json ${aws.createDate ?? ""}.`,
  ];
  const out = join(root, "crates/core/data/cloud-ranges.tsv");
  await writeFile(out, `${[...header, ...lines].join("\n")}\n`);
  console.log(`wrote ${lines.length} ranges to ${out}`);
}

async function geo() {
  const dir = join(root, "src-tauri/resources/ipdb");
  await mkdir(dir, { recursive: true });
  const now = new Date();
  // This month's file appears early in the month; fall back to last month.
  const months = [0, 1].map((back) => {
    const d = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() - back, 1));
    return d.toISOString().slice(0, 7);
  });
  const log = [];
  for (const kind of ["country", "asn"]) {
    let saved = false;
    for (const month of months) {
      const url = `https://download.db-ip.com/free/dbip-${kind}-lite-${month}.mmdb.gz`;
      try {
        const gz = Buffer.from(await (await get(url)).arrayBuffer());
        const db = gunzipSync(gz);
        await writeFile(join(dir, `dbip-${kind}-lite.mmdb`), db);
        const sha = createHash("sha256").update(db).digest("hex");
        log.push(`dbip-${kind}-lite.mmdb ${month} sha256:${sha}`);
        console.log(`wrote dbip-${kind}-lite.mmdb (${month}, sha256 ${sha})`);
        saved = true;
        break;
      } catch (e) {
        console.warn(`${url}: ${e.message}`);
      }
    }
    if (!saved) throw new Error(`couldn't download DB-IP ${kind} Lite`);
  }
  await writeFile(
    join(dir, "SOURCE.txt"),
    [
      "IP Geolocation by DB-IP (https://db-ip.com), CC BY 4.0",
      "(https://creativecommons.org/licenses/by/4.0/).",
      ...log,
      "",
    ].join("\n"),
  );
}

const args = new Set(process.argv.slice(2));
if (args.size === 0 || args.has("--ranges")) await ranges();
if (args.size === 0 || args.has("--geo")) await geo();
